[CmdletBinding()]
param(
    [switch]$DryRun,
    [switch]$SkipBuild,
    [string]$Workspace = 'G:\yaoyao-work',
    [ValidateSet('safe', 'coding', 'coding-online', 'research')]
    [string]$Mode = 'coding'
)

$ErrorActionPreference = 'Stop'

function Stop-Setup([string]$message, [int]$code) {
    Write-Output $message
    exit $code
}

$repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
if (-not (Test-Path -LiteralPath $Workspace -PathType Container)) {
    Stop-Setup "setup: workspace does not exist: $Workspace" 2
}
$workspacePath = [IO.Path]::GetFullPath($Workspace)

if (-not $env:LOCALAPPDATA) {
    Stop-Setup 'setup: LOCALAPPDATA is not set; personal mode targets Windows 10/11' 2
}
$appDir = Join-Path $env:LOCALAPPDATA 'yaoyao-agent'
$configPath = Join-Path $appDir 'personal-config.toml'
$template = Join-Path $repo 'examples\personal\config.toml'
$startLocal = Join-Path $repo 'scripts\gui\start.local.ps1'
if (-not (Test-Path -LiteralPath $template -PathType Leaf)) {
    Stop-Setup "setup: missing personal config template: $template" 2
}

$sandbox = if ($Mode -eq 'safe') { 'local' } else { 'app-container' }
$network = if ($Mode -eq 'coding-online') { 'internet' } else { 'deny' }
$provider = if ($env:AGENT_MODEL_PROVIDER) { $env:AGENT_MODEL_PROVIDER.Trim() } else { 'echo' }
if ($provider -eq 'openai') {
    foreach ($name in 'AGENT_MODEL_BASE_URL', 'AGENT_MODEL_NAME', 'AGENT_MODEL_API_KEY') {
        if (-not (Get-Item "Env:$name" -ErrorAction SilentlyContinue)) {
            Stop-Setup "setup: AGENT_MODEL_PROVIDER=openai requires $name (the value is never printed)" 2
        }
        if ([string]::IsNullOrWhiteSpace([Environment]::GetEnvironmentVariable($name))) {
            Stop-Setup "setup: AGENT_MODEL_PROVIDER=openai requires $name (the value is never printed)" 2
        }
    }
}

Write-Output 'setup: personal agent'
Write-Output "AGENT_USER_CONFIG=$configPath"
Write-Output "workspace=$workspacePath"
Write-Output "profile=$Mode"
Write-Output "AGENT_SANDBOX=$sandbox"
Write-Output "AGENT_SANDBOX_NETWORK=$network"
Write-Output "AGENT_MODEL_PROVIDER=$provider"
if ($DryRun) {
    Write-Output 'dry-run: no files written'
    exit 0
}

try {
    New-Item -ItemType Directory -Force -Path $appDir | Out-Null
    if (-not (Test-Path -LiteralPath $configPath)) {
        Copy-Item -LiteralPath $template -Destination $configPath
        Write-Output "setup: wrote $configPath"
    } else {
        Write-Output "setup: kept existing $configPath"
    }
} catch {
    Stop-Setup "setup: cannot write personal config: $($_.Exception.Message)" 1
}

try {
    if (-not (Test-Path -LiteralPath $startLocal)) {
        $networkLine = if ($network -eq 'internet') {
            "`$env:AGENT_SANDBOX_NETWORK = 'internet'"
        } else {
            "`$env:AGENT_SANDBOX_NETWORK = 'deny'"
        }
        $launcher = @"
# Generated by scripts\personal\setup.ps1. Keep secrets in the process environment,
# not this file, if you share or copy the checkout.
`$env:AGENT_USER_CONFIG = '$($configPath -replace "'", "''")'
`$env:AGENT_PROFILE = '$Mode'
`$env:AGENT_SANDBOX = '$sandbox'
$networkLine
# AGENT_DATA_DIR is intentionally left unset. An explicit value must be absolute
# and outside the workspace.
"@
        [IO.File]::WriteAllText($startLocal, $launcher, (New-Object System.Text.UTF8Encoding($false)))
        Write-Output "setup: wrote $startLocal"
    } else {
        Write-Output "setup: kept existing $startLocal"
    }
} catch {
    Stop-Setup "setup: cannot write launcher: $($_.Exception.Message)" 1
}

$cargo = Get-Command cargo -ErrorAction SilentlyContinue
if (-not $SkipBuild) {
    if (-not $cargo) {
        Stop-Setup 'setup: cargo is required to build agent.exe' 2
    }
    Push-Location $repo
    try {
        & $cargo.Source build -p agent
        if ($LASTEXITCODE -ne 0) { Stop-Setup 'setup: cargo build -p agent failed' 1 }
    } finally {
        Pop-Location
    }
}
$exe = Join-Path $repo 'target\debug\agent.exe'
if (-not (Test-Path -LiteralPath $exe -PathType Leaf)) {
    Stop-Setup "setup: missing $exe; run without -SkipBuild" 2
}

$savedWorkspace = $env:AGENT_WORKSPACE_DIR
$savedConfig = $env:AGENT_USER_CONFIG
$savedProfile = $env:AGENT_PROFILE
$savedSandbox = $env:AGENT_SANDBOX
$savedNetwork = $env:AGENT_SANDBOX_NETWORK
try {
    $env:AGENT_WORKSPACE_DIR = $workspacePath
    $env:AGENT_USER_CONFIG = $configPath
    $env:AGENT_PROFILE = $Mode
    $env:AGENT_SANDBOX = $sandbox
    $env:AGENT_SANDBOX_NETWORK = $network
    $doctorOutput = & $exe doctor 2>&1
    $doctorCode = $LASTEXITCODE
    $doctorOutput | ForEach-Object { Write-Output "  $_" }
} finally {
    $env:AGENT_WORKSPACE_DIR = $savedWorkspace
    $env:AGENT_USER_CONFIG = $savedConfig
    $env:AGENT_PROFILE = $savedProfile
    $env:AGENT_SANDBOX = $savedSandbox
    $env:AGENT_SANDBOX_NETWORK = $savedNetwork
}

if ($doctorCode -ne 0) {
    if ($sandbox -eq 'app-container') {
        Stop-Setup "setup: AppContainer is not ready. In an elevated PowerShell run:`n  `"$exe`" sandbox setup`nor install the boot task:`n  powershell -ExecutionPolicy Bypass -File `"$repo\scripts\sandbox-boot-task.ps1`" -Install" 2
    }
    Stop-Setup 'setup: agent doctor failed; fix the reported prerequisite and run setup again' 2
}
Write-Output 'setup: ready'