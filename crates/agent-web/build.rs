//! Embed the built page into the binary.
//!
//! M7 removed the hand-written `static/` shell: the page is now the Vite build
//! in `web/dist`. Compiling it in is what makes `agent web` a single file —
//! there is no second server, no directory to find next to the executable, and
//! no way for a page on disk to go stale relative to the API it calls.
//!
//! `web/dist` is checked in. A build therefore needs no Node toolchain, and the
//! same assets are embedded on a laptop and on CI. Regenerate them with
//! `pnpm --dir web build` after touching `web/src`; the `web` CI job fails when
//! the committed directory no longer matches its sources.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let dist = manifest.join("..").join("..").join("web").join("dist");
    let index = dist.join("index.html");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", dist.display());

    if !index.is_file() {
        panic!(
            "the page has not been built: {} is missing.\n\
             Run `pnpm --dir web install` once, then `pnpm --dir web build`.\n\
             The built directory is committed, so this is only needed after a \
             change to web/src.",
            index.display()
        );
    }

    let mut files = Vec::new();
    walk(&dist, &mut files);
    files.sort();

    let mut source = String::from(
        "// Generated by build.rs from web/dist. Do not edit.\n\
         pub(crate) struct Asset {\n\
         \x20   pub(crate) path: &'static str,\n\
         \x20   pub(crate) content_type: &'static str,\n\
         \x20   pub(crate) bytes: &'static [u8],\n\
         }\n\n",
    );
    let _ = writeln!(
        source,
        "pub(crate) static INDEX: &[u8] = include_bytes!({:?});\n",
        index.to_string_lossy()
    );
    source.push_str("pub(crate) static ASSETS: &[Asset] = &[\n");
    for file in &files {
        let relative = file.strip_prefix(&dist).expect("dist prefix");
        let key = relative.to_string_lossy().replace('\\', "/");
        // `index.html` is served at `/`, and every other file keeps its path.
        if key == "index.html" {
            continue;
        }
        let _ = writeln!(
            source,
            "    Asset {{ path: {key:?}, content_type: {:?}, bytes: include_bytes!({:?}) }},",
            content_type(&key),
            file.to_string_lossy()
        );
    }
    source.push_str("];\n");

    let out = PathBuf::from(env::var("OUT_DIR").expect("out dir")).join("web_assets.rs");
    fs::write(&out, source).expect("write embedded assets");
}

fn walk(dir: &Path, files: &mut Vec<PathBuf>) {
    let entries = fs::read_dir(dir).unwrap_or_else(|error| {
        panic!("cannot read {}: {error}", dir.display());
    });
    for entry in entries {
        let path = entry.expect("dist entry").path();
        if path.is_dir() {
            walk(&path, files);
        } else if path.is_file() {
            println!("cargo:rerun-if-changed={}", path.display());
            files.push(path);
        }
    }
}

/// The MIME type the browser needs. Spelled out rather than guessed: the set is
/// closed, and a wrong answer here is a page that silently does not run.
fn content_type(path: &str) -> &'static str {
    let extension = path.rsplit('.').next().unwrap_or("").to_ascii_lowercase();
    match extension.as_str() {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" | "map" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "gif" => "image/gif",
        "webp" => "image/webp",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "woff" => "font/woff",
        "ttf" => "font/ttf",
        "txt" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}
